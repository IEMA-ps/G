// Rules v16 test (waitlisted can be set but not cleared by the user while inviteOnly is on). Needs the Firestore emulator on 127.0.0.1:8092.
import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,setDoc,updateDoc,deleteField} from 'firebase/firestore';
const rules=readFileSync(new URL('./firestore.v16.proposed.rules',import.meta.url),'utf8');
const env=await initializeTestEnvironment({projectId:'demo-v16',firestore:{host:'127.0.0.1',port:8092,rules}});
let n=0;const ok=async(p,m)=>{try{await assertSucceeds(p);n++;}catch(e){console.error('FAIL (should work):',m,e.message.slice(0,200));process.exitCode=1;}};
const no=async(p,m)=>{try{await assertFails(p);n++;}catch(e){console.error('FAIL (should be denied):',m);process.exitCode=1;}};
const seed=async inviteOnly=>{await env.clearFirestore();await env.withSecurityRulesDisabled(async ctx=>{const db=ctx.firestore();const S=(p,id,d)=>setDoc(doc(db,p,id),d);
  await S('settings','app',{inviteOnly});
  await S('users','w1',{role:'CUSTOMER',firstName:'a',waitlisted:true,waitlistedAt:1});
  await S('users','w2',{role:'CUSTOMER',firstName:'b',waitlisted:true,waitlistedAt:1});
  await S('users','c1',{role:'CUSTOMER',firstName:'c'});
  await S('users','old1',{role:'CUSTOMER',firstName:'d',waitlisted:false});
  await S('users','adm',{role:'ADMIN',adminRole:'SUPER'});});};
const U=id=>env.authenticatedContext(id).firestore();
await seed(true);
await no(updateDoc(doc(U('w1'),'users','w1'),{waitlisted:false}),'inviteOnly on: user clears waitlisted');
await no(updateDoc(doc(U('w1'),'users','w1'),{waitlisted:deleteField()}),'inviteOnly on: user deletes waitlisted field');
await no(updateDoc(doc(U('w1'),'users','w1'),{waitlisted:false,waitlistedAt:null}),'clear with extra fields');
await ok(updateDoc(doc(U('w1'),'users','w1'),{waitlistCode:'ABC123',waitlistCodeAt:5}),'waitlisted user records the code he has (pending admin)');
await ok(updateDoc(doc(U('w1'),'users','w1'),{waitlisted:true,firstName:'z'}),'waitlisted user keeps true and edits profile');
await ok(updateDoc(doc(U('c1'),'users','c1'),{waitlisted:true,waitlistedAt:2}),'signup flow: user sets waitlisted true after signup');
await ok(updateDoc(doc(U('c1'),'users','c1'),{firstName:'x'}),'normal user edit');
await ok(updateDoc(doc(U('old1'),'users','old1'),{firstName:'x'}),'existing user with waitlisted:false edits profile');
await no(updateDoc(doc(U('w1'),'users','w2'),{waitlisted:false}),'user clears someone else');
await ok(updateDoc(doc(U('adm'),'users','w1'),{waitlisted:false}),'admin activates');
await ok(updateDoc(doc(U('adm'),'users','w2'),{waitlisted:false,waitlistedAt:null}),'admin activates (extra fields)');
await no(updateDoc(doc(U('w1'),'users','w1'),{banned:false}),'v15 ban protection still holds');
await seed(false);
await ok(updateDoc(doc(U('w1'),'users','w1'),{waitlisted:false}),'inviteOnly OFF: boot clears waitlisted (unchanged behavior)');
await ok(updateDoc(doc(U('w2'),'users','w2'),{waitlisted:false}),'inviteOnly OFF: second user');
console.log('passed',n);
await env.cleanup();
