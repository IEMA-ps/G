import assert from 'node:assert/strict';
import {offer2Config,paidOfferStores,bonusState,approvalAmounts,OFFER2_ID,bonusCardHTML} from './marketer-offer.js';
import {marketerOfferFor,MARKETER_OFFER} from './merchant-plans.js';
const S={marketerOffer2Enabled:true};
assert.deepEqual(offer2Config({}),{on:false,fee:250,months:3,flat:100,bonus:250,target:10});
assert.equal(offer2Config({offer2Months:5}).months,3);
assert.equal(offer2Config({marketerBonusTarget:0}).target,10);
assert.equal(offer2Config({offer2Fee:-4}).fee,250);
const sub=(m,at,extra={})=>({status:'APPROVED',offerId:OFFER2_ID,marketerId:'mk',merchantId:'m'+m,approvedAt:at,...extra});
const nine=Array.from({length:9},(_,i)=>sub(i,i+1));
assert.equal(paidOfferStores([...nine,sub(0,99)],'mk').length,9,'renewal of same store not counted');
assert.equal(paidOfferStores([{...sub(1,1),status:'PENDING'}],'mk').length,0);
assert.equal(paidOfferStores([{...sub(1,1),marketerId:'other'}],'mk').length,0);
assert.equal(paidOfferStores([{...sub(1,1),offerId:'MARKETER_PROFILE_6M'}],'mk').length,0,'old offer does not count');
let a=approvalAmounts({offerId:OFFER2_ID,marketerId:'mk',merchantId:'new',subs:nine,settings:S});
assert.deepEqual(a,{marketerAmount:100,marketerPercent:0,marketerBonus:250},'10th store pays 100 + 250');
a=approvalAmounts({offerId:OFFER2_ID,marketerId:'mk',merchantId:'m3',subs:nine,settings:S});
assert.equal(a.marketerBonus,0,'renewal does not trigger bonus');
a=approvalAmounts({offerId:OFFER2_ID,marketerId:'mk',merchantId:'x',subs:nine.slice(0,5),settings:S});
assert.equal(a.marketerBonus,0);assert.equal(a.marketerAmount,100);
const ten=[...nine,sub(9,10,{marketerBonus:250})];
a=approvalAmounts({offerId:OFFER2_ID,marketerId:'mk',merchantId:'y',subs:ten,settings:S});
assert.equal(a.marketerBonus,0,'bonus only once');
assert.equal(approvalAmounts({offerId:'MARKETER_PROFILE_6M',marketerId:'mk',merchantId:'y',subs:[],settings:S}),null);
assert.equal(approvalAmounts({offerId:OFFER2_ID,marketerId:null,merchantId:'y',subs:[],settings:S}),null);
let st=bonusState(nine,'mk',S);assert.equal(st.count,9);assert.equal(st.reached,false);assert.equal(st.credited,false);
st=bonusState(ten,'mk',S);assert.equal(st.reached,true);assert.equal(st.credited,true);
assert.match(bonusCardHTML(bonusState(nine.slice(0,3),'mk',S)),/3 من 10/);
// offer eligibility
const plan=(kind,months,id)=>({id,_id:id,kind,months,price:kind==='ORDERING'?400:200,active:true,model:'MERCHANT_V2'});
const m={subscriptionModel:'MERCHANT_V2',marketerId:'mk',subPlanType:null,subEndsAt:0};
let o=marketerOfferFor(m,plan('ORDERING',3,'ordering_3m_v2'),S);
assert.equal(o.offerId,OFFER2_ID);assert.equal(o.price,250);assert.equal(o.listPrice,400);assert.equal(o.months,3);
assert.equal(marketerOfferFor(m,plan('ORDERING',6,'ordering_6m_v2'),S),null,'only the configured months');
assert.equal(marketerOfferFor(m,plan('PROFILE',3,'profile_3m_v2'),S),null);
assert.equal(marketerOfferFor({...m,marketerOfferUsed:true},plan('ORDERING',3,'ordering_3m_v2'),S),null,'one use');
assert.equal(marketerOfferFor({...m,marketerId:null},plan('ORDERING',3,'ordering_3m_v2'),S),null);
assert.equal(marketerOfferFor(m,plan('ORDERING',3,'ordering_3m_v2'),{}),null,'default off');
assert.equal(marketerOfferFor(m,plan('ORDERING',3,'ordering_3m_v2'),{marketerOfferEnabled:true}),null,'old offer is for profile only');
const old=marketerOfferFor(m,plan('PROFILE',6,MARKETER_OFFER.planId),{marketerOfferEnabled:true});
assert.equal(old.offerId,MARKETER_OFFER.id);assert.equal(old.price,300);
assert.equal(marketerOfferFor(m,plan('PROFILE',6,MARKETER_OFFER.planId),{marketerOfferEnabled:true,marketerOffer2Enabled:true}),null,'old offer hidden when new one is on');
assert.equal(approvalAmounts({offerId:undefined,marketerId:'mk',merchantId:'m3',subs:nine,settings:S}),null,'renewals use the normal plan logic');
assert.equal(paidOfferStores([...nine,sub(3,50,{offerId:undefined})],'mk').length,9,'renewals never count');
console.log('marketer-offer tests ok');
