import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('./merchant-plans.js',import.meta.url),'utf8');
const P=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const now=Date.UTC(2026,10,22,12),day=86400000;
const merchant={id:'test',status:'ACTIVE',subscriptionModel:P.MODEL,subPlanType:'ORDERING',subEndsAt:now+day};
const profile={...merchant,subPlanType:'PROFILE'};
let checks=0;const check=(a,b)=>{assert.deepEqual(a,b);checks++;};
check(P.PLAN_TEMPLATES.map(p=>[p.kind,p.months,p.price]),[['PROFILE',3,200],['PROFILE',6,400],['PROFILE',12,600],['ORDERING',3,400],['ORDERING',6,800],['ORDERING',12,1200]]);
check(new Set(P.PLAN_TEMPLATES.map(p=>p.id)).size,6);
check(P.canOrder(merchant,false,now),true);
check(P.canOrder(profile,false,now),false);
check(P.visibleMerchant(profile,false,now),true);
check(P.canOrder({...merchant,subEndsAt:now},false,now),false);
check(P.visibleMerchant({...profile,status:'SUSPENDED'},false,now),false);
check(P.canOrder({...merchant,status:'PENDING'},false,now),false);
check(P.canOrder({status:'ACTIVE'},false,now),true);
check(P.canOrder({status:'ACTIVE'},true,now),false);
check(P.canOrder({status:'ACTIVE',subEndsAt:now+day},true,now),true);
check(P.canOrder({...merchant,subPlanType:null},false,now),false);
check(P.feeSnapshot({status:'ACTIVE'},100),{});
check(P.feeSnapshot(merchant,100).commissionAmount,2);
check(P.feeSnapshot(merchant,123.45).commissionAmount,2.47);
check(P.feeSnapshot(merchant,0).commissionAmount,0);
assert.throws(()=>P.feeSnapshot(profile,100));checks++;
const plan=P.PLAN_TEMPLATES[3];
check(P.termFor({...merchant,subEndsAt:now-1},plan,now).subPlanType,'ORDERING');
check(P.termFor({...merchant,subEndsAt:now+day},plan,now).subEndsAt,P.addCalendarMonths(now+day,3));
assert.throws(()=>P.termFor(profile,plan,now));checks++;
assert.throws(()=>P.termFor({subEndsAt:now+day},plan,now));checks++;
check(new Date(P.addCalendarMonths(Date.UTC(2027,0,31,12),1)).getUTCDate(),28);
check(new Date(P.addCalendarMonths(Date.UTC(2028,0,31,12),1)).getUTCDate(),29);
check(P.cairoMonth(Date.UTC(2026,0,31,23)), '2026-02');
check(P.cairoMonth({toMillis:()=>Date.UTC(2026,0,31,23)}),'2026-02');
check(P.cairoMonth(undefined),null);
const o={id:'o1',merchantId:'m1',status:'DELIVERED',...P.feeSnapshot(merchant,100),deliveredAt:Date.UTC(2026,0,31,23),createdAt:Date.UTC(2026,0,10)};
const rows=P.statements([o,{...o,id:'o2',status:'CANCELLED'},{...o,id:'o3',commissionModel:'LEGACY'},{...o,id:'o4',deliveredAt:null}]);
check(rows.length,1);check(rows[0].month,'2026-02');check(rows[0].fee,2);check(rows[0].count,1);
check(P.phoneHref('01000000000'),'tel:+201000000000');
check(P.phoneHref('javascript:alert(1)'), '');
check(P.mapHref({latitude:30,longitude:31}),'https://www.google.com/maps/search/?api=1&query=30%2C31');
check(P.mapHref({latitude:null,longitude:null,address:'عنوان'}),'https://www.google.com/maps/search/?api=1&query='+encodeURIComponent('عنوان'));
check(P.mapHref({}), '');
console.log(`PASS ${checks} merchant-plan checks`);
